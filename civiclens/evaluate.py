"""Generate a detailed evaluation report for the trained models.

Usage:
    python -m civiclens.evaluate
Writes reports/evaluation_report.md
"""

from __future__ import annotations

import numpy as np
import joblib
import pandas as pd
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix, mean_absolute_error

from civiclens.config import CATEGORIES, DATASET_PATH, REPORTS_DIR, URGENCY_LEVELS
from civiclens.nlp.category_model import CategoryModel
from civiclens.nlp.urgency_model import UrgencyModel
from civiclens.train import TEST_SPLIT_PATH

URGENCY_ORDER = {level: i for i, level in enumerate(URGENCY_LEVELS)}
REPORT_PATH = REPORTS_DIR / "evaluation_report.md"


def _confusion_table(y_true, y_pred, labels: list[str]) -> str:
    cm = confusion_matrix(y_true, y_pred, labels=labels)
    header = "| actual \\ predicted | " + " | ".join(labels) + " |"
    sep = "|" + "---|" * (len(labels) + 1)
    rows = [header, sep]
    for label, row in zip(labels, cm):
        rows.append(f"| **{label}** | " + " | ".join(str(x) for x in row) + " |")
    return "\n".join(rows)


def _selection_table(selection) -> str:
    lines = ["| model | mean macro-F1 (5-fold CV) | std |", "|---|---|---|"]
    for name, scores in selection.scores.items():
        marker = " ← selected" if name == selection.best_name else ""
        lines.append(f"| {name}{marker} | {np.mean(scores):.4f} | {np.std(scores):.4f} |")
    return "\n".join(lines)


def main() -> None:
    bundle = joblib.load(TEST_SPLIT_PATH)
    test_df: pd.DataFrame = bundle["test_df"]
    train_size: int = bundle["train_size"]
    category_selection = bundle["category_selection"]
    urgency_selection = bundle["urgency_selection"]

    full_df = pd.read_csv(DATASET_PATH)

    category_model = CategoryModel.load()
    urgency_model = UrgencyModel.load()

    texts = test_df["text"].tolist()

    # ---- Category evaluation ----
    y_true_cat = test_df["category"].tolist()
    y_pred_cat = category_model.predict(texts).tolist()
    cat_report = classification_report(y_true_cat, y_pred_cat, labels=CATEGORIES, digits=3, zero_division=0)
    cat_acc = accuracy_score(y_true_cat, y_pred_cat)
    cat_cm = _confusion_table(y_true_cat, y_pred_cat, CATEGORIES)

    # ---- Urgency evaluation ----
    y_true_urg = test_df["urgency"].tolist()
    y_pred_urg = urgency_model.predict(texts).tolist()
    urg_report = classification_report(y_true_urg, y_pred_urg, labels=URGENCY_LEVELS, digits=3, zero_division=0)
    urg_acc = accuracy_score(y_true_urg, y_pred_urg)
    urg_cm = _confusion_table(y_true_urg, y_pred_urg, URGENCY_LEVELS)

    true_idx = [URGENCY_ORDER[u] for u in y_true_urg]
    pred_idx = [URGENCY_ORDER[u] for u in y_pred_urg]
    mae = mean_absolute_error(true_idx, pred_idx)
    off_by_at_most_one = float(np.mean([abs(a - b) <= 1 for a, b in zip(true_idx, pred_idx)]))

    lines: list[str] = []
    lines.append("# CivicLens AI — Model Evaluation Report")
    lines.append("")
    lines.append("_Auto-generated by `python -m civiclens.evaluate`. Do not hand-edit — re-run instead._")
    lines.append("")
    lines.append("## Dataset")
    lines.append("")
    lines.append(f"- Total complaints (synthetic, see `civiclens/data/generate_dataset.py`): **{len(full_df)}**")
    lines.append(f"- Train / test split: **{train_size}** / **{len(test_df)}** (80/20, stratified by category)")
    lines.append("")
    lines.append("Category distribution:")
    lines.append("")
    lines.append(full_df["category"].value_counts().to_frame("count").to_markdown())
    lines.append("")
    lines.append("Urgency distribution:")
    lines.append("")
    lines.append(full_df["urgency"].value_counts().reindex(URGENCY_LEVELS).to_frame("count").to_markdown())
    lines.append("")

    lines.append("## Category classifier")
    lines.append("")
    lines.append(_selection_table(category_selection))
    lines.append("")
    lines.append(f"**Held-out test accuracy: {cat_acc:.4f}**")
    lines.append("")
    lines.append("```")
    lines.append(cat_report.rstrip())
    lines.append("```")
    lines.append("")
    lines.append("Confusion matrix (rows = actual, columns = predicted):")
    lines.append("")
    lines.append(cat_cm)
    lines.append("")

    lines.append("## Urgency classifier")
    lines.append("")
    lines.append(_selection_table(urgency_selection))
    lines.append("")
    lines.append(f"**Held-out test accuracy: {urg_acc:.4f}**")
    lines.append(
        f"**Ordinal mean absolute error (Low=0..Critical=3): {mae:.4f}** "
        f"— predictions land within one urgency level of the truth **{off_by_at_most_one * 100:.1f}%** of the time."
    )
    lines.append("")
    lines.append("```")
    lines.append(urg_report.rstrip())
    lines.append("```")
    lines.append("")
    lines.append("Confusion matrix (rows = actual, columns = predicted):")
    lines.append("")
    lines.append(urg_cm)
    lines.append("")

    lines.append("## Notes on interpreting these numbers")
    lines.append("")
    lines.append(
        "This dataset is synthetically generated from hand-written, urgency-tiered "
        "templates (see the dataset generator's module docstring for the full "
        "rationale) rather than scraped from a real 311-style system, since no "
        "such dataset was available to redistribute for this project. Accuracy "
        "this high is expected as a result: the vocabulary that signals urgency "
        "in the templates is consistent, which is exactly the kind of signal "
        "the lexicon and the classifiers are designed to pick up on. The "
        "realistic next step, called out in the README's Future Work section, "
        "is validating against real, messier citizen-submitted text."
    )
    lines.append("")

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines) + "\n")
    print(f"Wrote {REPORT_PATH}")
    print(f"Category test accuracy: {cat_acc:.4f}")
    print(f"Urgency test accuracy: {urg_acc:.4f}  (ordinal MAE: {mae:.4f})")


if __name__ == "__main__":
    main()
